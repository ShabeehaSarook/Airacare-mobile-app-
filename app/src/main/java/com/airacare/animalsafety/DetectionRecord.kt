package com.airacare.animalsafety

data class DetectionRecord(
    val detectedAtEpochMillis: Long,
    val detectedAtElapsedMillis: Long,
    val pipelineFrame: Long,
    val cameraSource: String,
    val trackId: Int?,
    val label: String,
    val confidence: Float,
    val riskLevel: RiskLevel,
    val riskReason: String,
    val pathZone: PathZone,
    val movementDirection: MovementDirection,
    val predictedPathCrossing: Boolean,
    val predictedPathCrossingSeconds: Float?,
    val predictedPathReason: String,
    val distanceMeters: Float?,
    val distanceSource: DistanceSource,
    val distanceQuality: Float?,
    val closingSpeedMetersPerSecond: Float?,
    val ttcSeconds: Float?,
    val vehicleSpeedMetersPerSecond: Float?,
    val vehicleSpeedKmh: Float?,
    val vehicleSpeedSource: String,
    val latitude: Double?,
    val longitude: Double?,
    val bearingDegrees: Float?,
    val horizontalAccuracyMeters: Float?,
    val bearingAccuracyDegrees: Float?,
    val imageWidth: Int,
    val imageHeight: Int,
    val rotationDegrees: Int,
    val boxLeft: Float,
    val boxTop: Float,
    val boxRight: Float,
    val boxBottom: Float,
    val visibilityState: VisibilityState,
    val visibilityQuality: Float,
    val enhancementEnabled: Boolean,
    val warningLevel: WarningLevel,
    val warningTriggered: Boolean,
    val audioTriggered: Boolean,
    val vibrationTriggered: Boolean,
    val warningMessage: String,
    val imagePath: String?,
    val syncStatus: String
) {
    companion object {
        const val SYNC_STATUS_LOCAL = "LOCAL"

        fun fromDetection(
            detection: AnimalDetection,
            cameraSource: String,
            pipelineFrame: Long,
            warningState: WarningState,
            nowEpochMillis: Long = System.currentTimeMillis(),
            nowElapsedMillis: Long = android.os.SystemClock.elapsedRealtime()
        ): DetectionRecord {
            val isWarningTarget = warningState.trackId != null && warningState.trackId == detection.trackId
            return DetectionRecord(
                detectedAtEpochMillis = nowEpochMillis,
                detectedAtElapsedMillis = nowElapsedMillis,
                pipelineFrame = pipelineFrame,
                cameraSource = cameraSource,
                trackId = detection.trackId,
                label = detection.label,
                confidence = detection.confidence,
                riskLevel = detection.riskLevel,
                riskReason = detection.riskReason,
                pathZone = detection.pathZone,
                movementDirection = detection.movementDirection,
                predictedPathCrossing = detection.predictedPathCrossing,
                predictedPathCrossingSeconds = detection.predictedPathCrossingSeconds,
                predictedPathReason = detection.predictedPathReason,
                distanceMeters = detection.distanceMeters,
                distanceSource = detection.distanceSource,
                distanceQuality = detection.distanceQuality,
                closingSpeedMetersPerSecond = detection.closingSpeedMetersPerSecond,
                ttcSeconds = detection.ttcSeconds,
                vehicleSpeedMetersPerSecond = detection.vehicleSpeedMetersPerSecond,
                vehicleSpeedKmh = detection.vehicleSpeedKmh,
                vehicleSpeedSource = detection.vehicleSpeedSource,
                latitude = detection.gpsLatitude,
                longitude = detection.gpsLongitude,
                bearingDegrees = detection.gpsBearingDegrees,
                horizontalAccuracyMeters = detection.gpsHorizontalAccuracyMeters,
                bearingAccuracyDegrees = detection.gpsBearingAccuracyDegrees,
                imageWidth = detection.imageWidth,
                imageHeight = detection.imageHeight,
                rotationDegrees = detection.rotationDegrees,
                boxLeft = detection.boundingBox.left,
                boxTop = detection.boundingBox.top,
                boxRight = detection.boundingBox.right,
                boxBottom = detection.boundingBox.bottom,
                visibilityState = detection.visibilityState,
                visibilityQuality = detection.visibilityQuality,
                enhancementEnabled = detection.enhancementEnabled,
                warningLevel = if (isWarningTarget) warningState.level else WarningLevel.NONE,
                warningTriggered = isWarningTarget && warningState.level != WarningLevel.NONE,
                audioTriggered = isWarningTarget && warningState.audioTriggered,
                vibrationTriggered = isWarningTarget && warningState.vibrationTriggered,
                warningMessage = if (isWarningTarget) warningState.message else "",
                imagePath = null,
                syncStatus = SYNC_STATUS_LOCAL
            )
        }
    }
}
